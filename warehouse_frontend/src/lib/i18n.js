export function t(key, lang = 'es') {
  const dict = translations[lang] || translations.es
  return dict[key] || key
}

export function initLanguage() {
  try {
    const raw = localStorage.getItem('wi-language')
    if (raw) {
      const parsed = JSON.parse(raw)
      const lang = parsed?.state?.language || 'es'
      document.documentElement.setAttribute('lang', lang)
      return lang
    }
  } catch { /* ignore */ }
  const lang = localStorage.getItem('wi_language') || 'es'
  document.documentElement.setAttribute('lang', lang)
  return lang
}
